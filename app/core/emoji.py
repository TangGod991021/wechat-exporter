# 只匹配短小的方括号代码，避免误伤正文里的普通方括号文本
_CODE_RE = re.compile(r'\[[^\[\]\r\n]{1,12}\]')


def convert(text):
    """把文本中的微信内置表情代码替换为 Unicode 表情"""
    if not text or '[' not in text:
        return text
    return _CODE_RE.sub(lambda m: EMOJI_MAP.get(m.group(0), m.group(0)), text)


def contains_code(text):
    """判断文本是否包含已知表情代码（用于按需转换）"""
    if not text or '[' not in text:
        return False
    return any(m.group(0) in EMOJI_MAP for m in _CODE_RE.finditer(text))
